export default function PriceFormatter(price, lang) {
  if (price === undefined || price === null || price === false) {
    return "";
  }
  if (lang === "AR") {
    const priceString = price.toLocaleString("ar-EG");
    const paddedPrice = priceString.padStart(12, " ");
    return paddedPrice;
  }
  const priceString = price.toLocaleString("en-US");
  const paddedPrice = priceString.padStart(12, " ");

  return paddedPrice;
}
